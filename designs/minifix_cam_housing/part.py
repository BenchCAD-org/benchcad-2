    points = (
        (-1.262 * scale, 3.841 * scale),
        (0.0, 6.942 * scale),
        (1.262 * scale, 3.841 * scale),
    )
    return (
        cq.Workplane("XY")
        .workplane(offset=z0)
        .polyline(points)
        .close()
        .extrude(depth)
        .val()
    )


